async def extract_text_from_pdf(file):
    content_type = getattr(file, "content_type", None)
    if content_type and content_type != "application/pdf":
        raise HTTPException(status_code=415, detail="Invalid file type. Please upload a PDF file.")

    pdf_bytes = file.file.read()
    if b"%PDF-" not in pdf_bytes[:1024]:
        raise HTTPException(status_code=415, detail="Invalid file type. Please upload a PDF file.")

    try:
        with pdfplumber.open(io.BytesIO(pdf_bytes)) as pdf:
            for page in pdf.pages:
                page_img = page.to_image(resolution=200).original
                text = pytesseract.image_to_string(page_img)

                if text:
                    return text + "\n"
                return {"message": "Provided Pdf may be empty. Please upload a valid PDF."}
    except Exception:
        print("Error in extracting data through OCR engine; falling back to Gemini.")
        try:
            response = genai_client.models.generate_content(
            model="gemini-2.5-flash",
            contents=[
            types.Part.from_text(text="please perform OCR on this scanned PDF." \
            "Extract text from given pdf exactly as it appears, preserving formating were possible"),
            types.Part.from_bytes(data=pdf_bytes,mime_type="application/pdf")
            ]
        )
            response_text=response.text
            if response_text:
                print(f"Text extracted from {getattr(file, 'filename', 'uploaded file')}")
                return response_text
            else:
                raise HTTPException(status_code=500,detail="The response is not generated by gemini")
        except Exception as e:
            raise HTTPException(status_code=500,detail=f"Error in model gemini-2.5-flash error:{str(e)}")